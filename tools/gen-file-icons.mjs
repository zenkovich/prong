#!/usr/bin/env node
/**
 * Builds the file-icon set from Material Icon Theme (MIT, https://github.com/material-extensions/vscode-material-icon-theme):
 * - copies every icon the file/folder mappings use into public/file-icons/ (served as static files, so the JS bundle
 *   only carries the lookup tables), plus the theme's LICENSE;
 * - writes src/ui/fileIconMap.generated.ts with the lookup tables. Folder names are stored canonical (no leading
 *   "." "_" "-" and no trailing "_"), matching how FileIcon normalises names.
 *
 *   node tools/gen-file-icons.mjs
 */
import { copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const pkgDir = path.dirname(require.resolve('material-icon-theme/package.json'));
const man = require('material-icon-theme').generateManifest();
const OUT = path.join(ROOT, 'public/file-icons');
const iconFile = (name) => path.join(pkgDir, 'icons', path.basename(man.iconDefinitions[name]?.iconPath ?? `${name}.svg`));
const canon = (n) => n.toLowerCase().replace(/^[._-]+/, '').replace(/_+$/, '');

const used = new Set([man.file, man.folder, man.folderExpanded]);
const pick = (obj, key = (k) => k.toLowerCase()) => {
  const out = {};
  for (const [k, v] of Object.entries(obj ?? {})) {
    if (!existsSync(iconFile(v))) continue;
    out[key(k)] = v;
    used.add(v);
  }
  return out;
};
// file names that VS Code resolves through a language id rather than a file name
const LANGUAGE_FILES = { dockerfile: 'dockerfile', containerfile: 'dockerfile', 'gnumakefile': 'makefile', mk: 'makefile' };
const ext = pick(man.fileExtensions);
const name = pick(man.fileNames);
for (const [file, lang] of Object.entries(LANGUAGE_FILES)) {
  const icon = man.languageIds[lang];
  if (icon && existsSync(iconFile(icon))) {
    if (file === 'mk') ext[file] = icon;
    else name[file] ??= icon;
    used.add(icon);
  }
}
const folder = {};
for (const [k, v] of Object.entries(man.folderNames)) {
  if (!existsSync(iconFile(v))) continue;
  const c = canon(k);
  if (!c || folder[c]) continue;
  folder[c] = v;
  used.add(v);
  const open = man.folderNamesExpanded[k];
  if (open && existsSync(iconFile(open))) used.add(open);
}
const light = {
  ext: pick(man.light?.fileExtensions),
  name: pick(man.light?.fileNames),
  folder: Object.fromEntries(Object.entries(man.light?.folderNames ?? {}).filter(([, v]) => existsSync(iconFile(v))).map(([k, v]) => (used.add(v), [canon(k), v]))),
};
for (const v of Object.values(man.light?.folderNamesExpanded ?? {})) if (existsSync(iconFile(v))) used.add(v);

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });
let bytes = 0;
for (const n of used) {
  const src = iconFile(n);
  if (!existsSync(src)) continue;
  copyFileSync(src, path.join(OUT, `${n}.svg`));
  bytes += readFileSync(src).length;
}
copyFileSync(path.join(pkgDir, 'LICENSE'), path.join(OUT, 'LICENSE.txt'));

const version = JSON.parse(readFileSync(path.join(pkgDir, 'package.json'), 'utf8')).version;
const table = { file: man.file, folder: man.folder, folderOpen: man.folderExpanded, ext, name, folderNames: folder, light };
writeFileSync(
  path.join(ROOT, 'src/ui/fileIconMap.generated.ts'),
  `// Generated by tools/gen-file-icons.mjs from material-icon-theme ${version} (MIT). Do not edit.\n` +
    `// Icons live in public/file-icons/<name>.svg; folders open as <name>-open.svg when that file exists.\n` +
    `export const ICONS: {\n  file: string;\n  folder: string;\n  folderOpen: string;\n  ext: Record<string, string>;\n  name: Record<string, string>;\n  folderNames: Record<string, string>;\n  light: { ext: Record<string, string>; name: Record<string, string>; folder: Record<string, string> };\n} = ${JSON.stringify(table)};\n` +
    `export const OPEN_FOLDERS: string[] = ${JSON.stringify([...used].filter((n) => n.endsWith('-open')).sort())};\n`,
);
console.log(`file icons: ${used.size} svg (${(bytes / 1024).toFixed(0)} KB) · ${Object.keys(ext).length} extensions · ${Object.keys(name).length} names · ${Object.keys(folder).length} folders`);
