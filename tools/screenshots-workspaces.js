const { chromium } = require('playwright');
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROME, headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  const errors = [];
  page.on('pageerror', (e) => errors.push(e.message));
  page.on('console', (m) => m.type() === 'error' && errors.push(m.text().slice(0, 200)));
  await page.goto('http://localhost:8099/', { waitUntil: 'load', timeout: 120000 });
  await page.waitForSelector('text=Repositories', { timeout: 120000 });
  await page.screenshot({ path: 'w1-welcome-work.png' });
  await page.click('text=@home');
  await page.waitForTimeout(500);
  await page.screenshot({ path: 'w2-welcome-home.png' });
  await page.click('text=~/home/PetStory');
  await page.waitForTimeout(700);
  await page.click('[aria-label="Workspace"]');
  await page.waitForTimeout(400);
  await page.screenshot({ path: 'w3-ws-menu.png' });
  await page.keyboard.press('Escape');
  await page.click('[aria-label="Preferences (⌘,)"]');
  await page.waitForTimeout(500);
  await page.screenshot({ path: 'w4-prefs.png' });
  await page.click('text=Solar');
  await page.waitForTimeout(300);
  await page.click('text=125%');
  await page.waitForTimeout(500);
  await page.screenshot({ path: 'w5-solar-125.png' });
  await page.click('text=Phosphor'); await page.click('text=100%'); await page.waitForTimeout(300);
  await page.keyboard.press('Escape'); await page.waitForTimeout(300);
  await page.screenshot({ path: 'w6-phosphor.png' });
  console.log('errors:', errors.length, errors.join(' | '));
  await browser.close();
})().catch((e) => { console.error(e.message); process.exit(1); });
